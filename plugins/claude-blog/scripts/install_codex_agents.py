#!/usr/bin/env python3
"""Install Claude plugin agent definitions as project-scoped Codex agents."""

from __future__ import annotations

import argparse
import json
import re
import sys
import tomllib
from pathlib import Path
from typing import Any


PLUGIN_ROOT = Path(__file__).resolve().parent.parent
MANIFEST_PATH = PLUGIN_ROOT / ".codex-plugin" / "plugin.json"
MANIFEST = json.loads(MANIFEST_PATH.read_text(encoding="utf-8"))
PLUGIN_NAME = MANIFEST["name"]
MARKER = f"# Generated by {PLUGIN_NAME}/scripts/install_codex_agents.py"


def split_document(text: str) -> tuple[list[str], str]:
    """Return YAML-frontmatter lines and the Markdown body."""
    lines = text.splitlines()
    if not lines or lines[0].strip() != "---":
        raise ValueError("agent file must start with YAML frontmatter")
    try:
        end = next(i for i in range(1, len(lines)) if lines[i].strip() == "---")
    except StopIteration as exc:
        raise ValueError("agent file has unterminated YAML frontmatter") from exc
    return lines[1:end], "\n".join(lines[end + 1 :]).strip() + "\n"


def parse_frontmatter(lines: list[str]) -> dict[str, Any]:
    """Parse the small YAML subset used by Claude agent definitions."""
    result: dict[str, Any] = {}
    index = 0
    while index < len(lines):
        match = re.match(r"^([A-Za-z][A-Za-z0-9_-]*):(?:\s*(.*))?$", lines[index])
        if not match:
            index += 1
            continue
        key, raw_value = match.group(1), (match.group(2) or "").strip()
        index += 1

        if raw_value in {">", ">-", "|", "|-"}:
            block: list[str] = []
            while index < len(lines) and (not lines[index] or lines[index][0].isspace()):
                block.append(lines[index].strip())
                index += 1
            result[key] = " ".join(filter(None, block)) if raw_value.startswith(">") else "\n".join(block)
            continue

        if not raw_value:
            items: list[str] = []
            while index < len(lines):
                item_match = re.match(r"^\s+-\s+(.+?)\s*$", lines[index])
                if not item_match:
                    break
                items.append(item_match.group(1))
                index += 1
            result[key] = items
            continue

        result[key] = raw_value
    return result


def tool_names(value: Any) -> list[str]:
    if isinstance(value, list):
        return [str(item).strip() for item in value if str(item).strip()]
    if not value:
        return []
    uncommented = str(value).split("#", 1)[0]
    return [item.strip() for item in uncommented.split(",") if item.strip()]


def codex_name(name: str) -> str:
    """Codex custom-agent names use underscores for stable direct invocation."""
    return name.replace("-", "_")


def toml_string(value: str) -> str:
    """Encode a TOML basic string without invalid JSON surrogate escapes."""
    return json.dumps(value, ensure_ascii=False)


def build_agent(source: Path) -> tuple[str, str]:
    header_lines, body = split_document(source.read_text(encoding="utf-8"))
    metadata = parse_frontmatter(header_lines)
    source_name = str(metadata.get("name") or source.stem)
    name = codex_name(source_name)
    description = str(metadata.get("description") or f"Codex port of {source_name}.")
    tools = {tool.lower() for tool in tool_names(metadata.get("tools"))}
    sandbox_mode = "workspace-write" if tools.intersection({"write", "edit"}) else "read-only"
    plugin_root = str(PLUGIN_ROOT)
    preamble = (
        f"This is the Codex-compatible form of the {source_name} Claude Code agent.\n"
        f"Supporting plugin root: {plugin_root}\n"
        "Resolve relative paths beginning with scripts/, skills/, agents/, or templates/ "
        "from that plugin root. Use Codex-native shell, search, file, web, and delegation "
        "tools instead of treating Claude tool names as literal commands.\n\n"
    )
    content = "\n".join(
        [
            MARKER,
            f"name = {toml_string(name)}",
            f"description = {toml_string(description)}",
            f"sandbox_mode = {toml_string(sandbox_mode)}",
            f"developer_instructions = {toml_string(preamble + body)}",
            "",
        ]
    )
    tomllib.loads(content)
    return name, content


def build_all() -> dict[str, str]:
    sources = sorted((PLUGIN_ROOT / "agents").glob("*.md"))
    if not sources:
        raise ValueError(f"no Claude agents found under {PLUGIN_ROOT / 'agents'}")
    generated = dict(build_agent(source) for source in sources)
    if len(generated) != len(sources):
        raise ValueError("two Claude agents normalize to the same Codex name")
    return generated


def install(project_root: Path, *, force: bool = False) -> list[Path]:
    target_dir = project_root.resolve() / ".codex" / "agents"
    target_dir.mkdir(parents=True, exist_ok=True)
    written: list[Path] = []
    for name, content in build_all().items():
        target = target_dir / f"{name}.toml"
        if target.exists() and MARKER not in target.read_text(encoding="utf-8") and not force:
            raise FileExistsError(f"refusing to replace unmanaged Codex agent: {target}")
        target.write_text(content, encoding="utf-8")
        written.append(target)
    return written


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--project-root", type=Path, default=Path.cwd())
    parser.add_argument("--check", action="store_true", help="validate conversion without writing files")
    parser.add_argument("--force", action="store_true", help="replace colliding unmanaged agent files")
    parser.add_argument("--json", action="store_true", dest="as_json")
    args = parser.parse_args()

    try:
        generated = build_all()
        paths = [] if args.check else install(args.project_root, force=args.force)
    except (OSError, ValueError) as exc:
        print(str(exc), file=sys.stderr)
        return 1

    payload = {
        "plugin": PLUGIN_NAME,
        "agents": len(generated),
        "mode": "check" if args.check else "install",
        "written": [str(path) for path in paths],
    }
    if args.as_json:
        print(json.dumps(payload, indent=2))
    else:
        print(f"{payload['mode']} complete: {len(generated)} Codex agents for {PLUGIN_NAME}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
